#!/usr/bin/env python3
"""Generates the mobium-bench datapack (benchmark/mobium-bench).

Run from anywhere: python3 benchmark/generate.py. The output is committed, so nobody needs to run this to use the
pack; edit this script and regenerate instead of editing the .mcfunction files by hand.

Every scene is built at the same spot, ORIGIN, in a classic superflat world with the seed "mobium" (structures on).
ORIGIN was chosen so that the nearest village is about 600 blocks away (the gametest checks this). Villages must stay
enabled because map_wall makes real maps with an exploration_map loot function, which needs a structure to point at.
"""

from pathlib import Path

PACK = Path(__file__).resolve().parent / "mobium-bench"
NAMESPACE = "mobium-bench"
DATA_FORMAT = 121  # Minecraft 26.3 data pack format (version.json: pack_version.data_major)

X0, Z0 = -3840, -2816  # scene origin; camera stands here and looks south (+z)
FLOOR = -61  # top of the classic superflat grass layer
GROUND = FLOOR + 1  # first air block

# The region every scene may use; reset clears it.
MIN_X, MAX_X = X0 - 40, X0 + 39
MIN_Z, MAX_Z = Z0 - 16, Z0 + 63
TOP = GROUND + 40

TAG = "mobium_bench"
OBJECTIVE = "mobium_bench"  # holds #ready = 1 once a scene is built (read by the gametest)


def center(block: int) -> str:
    """The centre of a block along one axis (block + 0.5, also correct for negative coordinates)."""
    return f"{block + 0.5:g}"


def write(path: str, lines: list[str]) -> None:
    file = PACK / path
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def scene(name: str, description: str, camera: tuple[float, float, float, float, float], build: list[str]) -> None:
    """A scene is two functions: <name> teleports the player and schedules internal/build_<name>, which waits until
    the region is loaded, clears it, builds the scene and announces that it is ready."""
    x, y, z, yaw, pitch = camera
    write(f"data/{NAMESPACE}/function/{name}.mcfunction", [
        f"# {description}",
        "# Run as the player: /function mobium-bench:" + name,
        f"function {NAMESPACE}:internal/settings",
        f"scoreboard players set #ready {OBJECTIVE} 0",
        "gamemode spectator @s",
        f"tp @s {x} {y} {z} {yaw} {pitch}",
        f"forceload add {MIN_X} {MIN_Z} {MAX_X} {MAX_Z}",
        f'tellraw @s {{"text":"Building {name}, please wait…","color":"gray"}}',
        f"schedule function {NAMESPACE}:internal/build_{name} 20t replace",
    ])
    corners = [(MIN_X, MIN_Z), (MIN_X, MAX_Z), (MAX_X, MIN_Z), (MAX_X, MAX_Z), (X0, Z0 + 24)]
    wait = [
        f"execute unless loaded {cx} {GROUND} {cz} run return run schedule function {NAMESPACE}:internal/build_{name} 10t replace"
        for cx, cz in corners
    ]
    write(f"data/{NAMESPACE}/function/internal/build_{name}.mcfunction", [
        "# Generated by benchmark/generate.py",
        *wait,
        f"function {NAMESPACE}:internal/reset",
        *build,
        f"scoreboard players set #ready {OBJECTIVE} 1",
        f'tellraw @a {{"text":"Scene {name} is ready","color":"green"}}',
    ])


def settings() -> list[str]:
    return [
        "# Generated by benchmark/generate.py: world settings shared by every scene",
        "gamerule advance_time false",
        "gamerule advance_weather false",
        "gamerule spawn_mobs false",
        "gamerule spawn_monsters false",
        "gamerule spawn_patrols false",
        "gamerule spawn_phantoms false",
        "gamerule spawn_wandering_traders false",
        "gamerule random_tick_speed 0",
        "gamerule mob_griefing false",
        "gamerule max_block_modifications 1000000",
        "time set noon",
        "weather clear",
        "difficulty easy",
        f"scoreboard objectives add {OBJECTIVE} dummy",
    ]


def reset() -> list[str]:
    area = f"x={MIN_X},y={FLOOR - 3},z={MIN_Z},dx={MAX_X - MIN_X + 1},dy={TOP - FLOOR + 6},dz={MAX_Z - MIN_Z + 1}"
    return [
        "# Generated by benchmark/generate.py: empties the scene region",
        f"kill @e[type=!minecraft:player,{area}]",
        f"kill @e[type=minecraft:item,{area}]",
        f"fill {MIN_X} {GROUND} {MIN_Z} {MAX_X} {TOP} {MAX_Z} minecraft:air strict",
        f"fill {MIN_X} {FLOOR} {MIN_Z} {MAX_X} {FLOOR} {MAX_Z} minecraft:grass_block strict",
    ]


MOBS = ["minecraft:cow", "minecraft:villager", "minecraft:zombie"]


def mob(kind: str, x: int, z: int, ai: bool) -> str:
    nbt = [
        "Silent:1b",
        "PersistenceRequired:1b",
        "Rotation:[180f,0f]",
        f'Tags:["{TAG}"]',
    ]
    if not ai:
        nbt.insert(0, "NoAI:1b")
    if kind == "minecraft:zombie":
        # A helmet keeps zombies from burning at noon; it must be unbreakable, or the sun wears it out within about
        # two minutes and a third of the mobs burn to death during the second run (Mob.burnUndead).
        nbt.append('equipment:{head:{id:"minecraft:leather_helmet",count:1,components:{"minecraft:unbreakable":{}}}}')
    return f"summon {kind} {center(x)} {GROUND} {center(z)} {{{','.join(nbt)}}}"


def mob_grid():
    """500 cells: 25 columns x 20 rows, two blocks apart, in front of the camera."""
    for row in range(20):
        for column in range(25):
            yield X0 - 24 + column * 2, Z0 + 12 + row * 2, MOBS[(row + column) % len(MOBS)]


def mob_pen_static() -> list[str]:
    return [mob(kind, x, z, ai=False) for x, z, kind in mob_grid()]


def mob_pen_live() -> list[str]:
    # Barrier walls two blocks high with a 1x1 hole for every mob, so the mobs walk in place.
    lines = [f"fill {X0 - 25} {GROUND} {Z0 + 11} {X0 + 25} {GROUND + 1} {Z0 + 51} minecraft:barrier strict"]
    for x, z, _ in mob_grid():
        lines.append(f"fill {x} {GROUND} {z} {x} {GROUND + 1} {z} minecraft:air strict")
    lines += [mob(kind, x, z, ai=True) for x, z, kind in mob_grid()]
    return lines


SIGN_TEXT = [
    ["Iron", "Copper", "Gold", "Diamonds"],
    ["Redstone", "Repeaters", "Comparators", "Hoppers"],
    ["Wool", "Dyes", "Carpets", "Banners"],
    ["Food", "Bread", "Carrots", "Steak"],
    ["Stone", "Andesite", "Diorite", "Granite"],
]
SIGN_COLORS = ["black", "light_blue", "yellow", "lime", "white"]


def storage_room() -> list[str]:
    # 1,000 closed single chests in a wall 50 wide and 20 high, facing the camera.
    lines = [
        f"fill {X0 - 25} {GROUND} {Z0 + 30} {X0 + 24} {GROUND + 19} {Z0 + 30} "
        "minecraft:chest[facing=north,type=single] strict"
    ]
    # 300 standing signs with four lines each, every fourth with glowing coloured text.
    index = 0
    for row in range(10):
        for column in range(30):
            text = SIGN_TEXT[index % len(SIGN_TEXT)]
            messages = ",".join(f'"{line}"' for line in text)
            glowing = index % 4 == 3
            extra = f',color:"{SIGN_COLORS[index % len(SIGN_COLORS)]}",has_glowing_text:1b' if glowing else ""
            x, z = X0 - 15 + column, Z0 + 10 + row * 2
            lines.append(
                f"setblock {x} {GROUND} {z} minecraft:oak_sign[rotation=8]"
                f"{{front_text:{{messages:[{messages}]{extra}}}}} strict"
            )
            index += 1
    return lines


SHELF_ITEMS = [
    ["minecraft:diamond", "minecraft:compass", "minecraft:apple"],
    ["minecraft:iron_ingot", "minecraft:clock", "minecraft:bread"],
    ["minecraft:emerald", "minecraft:book", "minecraft:recovery_compass"],
]


def map_wall() -> list[str]:
    wall_z = Z0 + 21
    lines = [f"fill {X0 - 20} {GROUND} {wall_z} {X0 + 19} {GROUND + 13} {wall_z} minecraft:stone strict"]
    # 400 item frames (40 x 10) on the wall, each with its own filled map.
    for y in range(GROUND + 4, GROUND + 14):
        for x in range(X0 - 20, X0 + 20):
            lines.append(
                f"summon minecraft:item_frame {center(x)} {center(y)} {center(wall_z - 1)} "
                # Pos makes the entity's position known while block_pos is read, which must be within 16 blocks.
                f"{{Pos:[{center(x)}d,{center(y)}d,{center(wall_z - 1)}d],Facing:2b,Fixed:1b,"
                f'block_pos:[I;{x},{y},{wall_z - 1}],Tags:["{TAG}","mobium_map"]}}'
            )
    lines.append(
        f"execute as @e[type=minecraft:item_frame,tag=mobium_map] at @s "
        f"run loot replace entity @s contents loot {NAMESPACE}:map"
    )
    # 120 shelves (40 x 3) below the maps, three items each; compasses and clocks animate.
    for row in range(3):
        items = SHELF_ITEMS[row]
        stacks = ",".join(f'{{Slot:{slot}b,id:"{item}",count:1}}' for slot, item in enumerate(items))
        y = GROUND + row
        lines.append(
            f"fill {X0 - 20} {y} {wall_z - 1} {X0 + 19} {y} {wall_z - 1} "
            f"minecraft:oak_shelf[facing=north]{{Items:[{stacks}]}} strict"
        )
    return lines


DISPLAY_BLOCKS = [
    "minecraft:stone_bricks",
    "minecraft:oak_planks",
    "minecraft:glass",
    "minecraft:gold_block",
    "minecraft:copper_block",
    "minecraft:moss_block",
    "minecraft:amethyst_block",
    "minecraft:quartz_block",
]
DISPLAY_ITEMS = [
    "minecraft:diamond_sword",
    "minecraft:apple",
    "minecraft:shield",
    "minecraft:bow",
    "minecraft:lantern",
    "minecraft:flower_pot",
]
# Quaternion for 45 degrees around Y.
Y45 = "[0f,0.38268343f,0f,0.9238795f]"
IDENTITY = "[0f,0f,0f,1f]"


def display_build() -> list[str]:
    lines = []
    # 400 block displays: a wall 20 wide, 10 high and 2 deep, every other cube turned by 45 degrees.
    index = 0
    for depth in range(2):
        for y in range(10):
            for column in range(20):
                block = DISPLAY_BLOCKS[index % len(DISPLAY_BLOCKS)]
                rotation = Y45 if index % 2 else IDENTITY
                x, z = X0 - 20 + column * 2, Z0 + 20 + depth * 2
                lines.append(
                    f"summon minecraft:block_display {x} {GROUND + y} {z} "
                    f'{{block_state:"{block}",'
                    f"transformation:{{left_rotation:{IDENTITY},right_rotation:{rotation},"
                    f"translation:[-0.45f,0f,-0.45f],scale:[0.9f,0.9f,0.9f]}},"
                    f'Tags:["{TAG}"]}}'
                )
                index += 1
    # 100 item displays (10 x 10) floating in front of the wall.
    for row in range(10):
        for column in range(10):
            item = DISPLAY_ITEMS[(row + column) % len(DISPLAY_ITEMS)]
            x, y, z = X0 - 9 + column * 2, GROUND + 1 + row, Z0 + 16
            lines.append(
                f"summon minecraft:item_display {center(x)} {center(y)} {center(z)} "
                f'{{item:{{id:"{item}",count:1}},Tags:["{TAG}"]}}'
            )
    return lines


GALLERY_SKULLS = [
    "skeleton_skull", "wither_skeleton_skull", "zombie_head", "creeper_head", "dragon_head", "piglin_head",
    "player_head",
]
GALLERY_CHESTS = [
    # (x offset, block state)
    (-8, "chest[facing=north,type=single]"),
    # facing north: the left half connects east (ChestBlock.getConnectedDirection)
    (-6, "chest[facing=north,type=left]"),
    (-5, "chest[facing=north,type=right]"),
    (-3, "trapped_chest[facing=north,type=single]"),
    (-1, "ender_chest[facing=north]"),
    (1, "copper_chest[facing=north,type=single]"),
    (2, "oxidized_copper_chest[facing=north,type=single]"),
    (4, "shulker_box[facing=up]"),
    (5, "red_shulker_box[facing=north]"),
    (6, "blue_shulker_box[facing=up]"),
]
GALLERY_SIGNS = [
    # (x offset, front text messages, extra front_text fields); obfuscated and sprite text stay on vanilla
    (-8, '"Plain","oak","wall","sign"', ""),
    (-6, '"Black","glow","ink",""', ',color:"black",has_glowing_text:1b'),
    (-4, '"Yellow","glow","ink","outline"', ',color:"yellow",has_glowing_text:1b'),
    (-2, '{text:"Bold",bold:1b},{text:"Italic",italic:1b},{text:"Under",underlined:1b},{text:"Strike",strikethrough:1b}', ""),
    (0, '{text:"Red",color:"red"},{text:"Green",color:"green"},{text:"Blue",color:"blue"},"Mixed"', ""),
    # Obfuscated spaces look the same every frame (Font.getGlyph skips spaces), but the rule still refuses the style.
    (2, '"Obfuscated",{text:"    ",obfuscated:1b},"stays","vanilla"', ""),
    (4, '"Sprite",{type:"object",object:"atlas",sprite:"block/stone"},"stays","vanilla"', ""),
    (6, '"Light","blue","dye",""', ',color:"light_blue"'),
]

GALLERY_SHELVES = [
    (-5, ["diamond", "apple", "book"]),
    (-1, ["iron_ingot", "clock", "emerald"]),
    (3, ["compass", "bread", "gold_ingot"]),
]


def cache_gallery() -> list[str]:
    """Every type the static cache handles, with the variants its rules tell apart, close to the camera."""
    lines = []
    # Row 1: skulls (one dragon head powered by a redstone block below, so its mouth moves) and decorated pots.
    for index, skull in enumerate(GALLERY_SKULLS):
        lines.append(f"setblock {X0 - 8 + index} {GROUND} {Z0 + 6} minecraft:{skull}[rotation=8] strict")
    lines.append(f"setblock {X0} {FLOOR} {Z0 + 6} minecraft:redstone_block strict")
    lines.append(f"setblock {X0} {GROUND} {Z0 + 6} minecraft:dragon_head[rotation=8,powered=true] strict")
    lines.append(f"setblock {X0 + 2} {GROUND} {Z0 + 6} minecraft:decorated_pot[facing=north] strict")
    lines.append(
        f"setblock {X0 + 4} {GROUND} {Z0 + 6} minecraft:decorated_pot[facing=north]"
        '{sherds:{front:"minecraft:angler_pottery_sherd",left:"minecraft:heart_pottery_sherd",'
        'right:"minecraft:skull_pottery_sherd",back:"minecraft:brick"}} strict'
    )
    # Row 2: chests of every kind and shulker boxes.
    for offset, state in GALLERY_CHESTS:
        lines.append(f"setblock {X0 + offset} {GROUND} {Z0 + 9} minecraft:{state} strict")
    # Row 3: a wall with wall signs, and hanging signs from a beam above them.
    lines.append(f"fill {X0 - 9} {GROUND} {Z0 + 13} {X0 + 7} {GROUND + 4} {Z0 + 13} minecraft:stone_bricks strict")
    lines.append(f"fill {X0 - 9} {GROUND + 4} {Z0 + 12} {X0 + 7} {GROUND + 4} {Z0 + 12} minecraft:stone_bricks strict")
    for offset, messages, extra in GALLERY_SIGNS:
        lines.append(
            f"setblock {X0 + offset} {GROUND + 1} {Z0 + 12} minecraft:oak_wall_sign[facing=north]"
            f"{{front_text:{{messages:[{messages}]{extra}}}}} strict"
        )
    # Shelves on the wall between the wall signs: plain items, a clock (time stands still) and a compass.
    for offset, items in GALLERY_SHELVES:
        stacks = ",".join(f'{{Slot:{slot}b,id:"minecraft:{item}",count:1}}' for slot, item in enumerate(items))
        lines.append(
            f"setblock {X0 + offset} {GROUND + 2} {Z0 + 12} minecraft:oak_shelf[facing=north]{{Items:[{stacks}]}} strict"
        )
    for index, offset in enumerate(range(-7, 8, 4)):
        glowing = ',color:"lime",has_glowing_text:1b' if index % 2 else ""
        lines.append(
            f"setblock {X0 + offset} {GROUND + 3} {Z0 + 12} minecraft:spruce_hanging_sign[rotation=8,attached=true]"
            f'{{front_text:{{messages:["Hanging","sign","{index}",""]{glowing}}},'
            f'back_text:{{messages:["Back","text","",""]}}}} strict'
        )
    return lines


def main() -> None:
    write("pack.mcmeta", [
        "{",
        '    "pack": {',
        '        "description": "Mobium benchmark scenes",',
        f'        "min_format": {DATA_FORMAT},',
        f'        "max_format": {DATA_FORMAT}',
        "    }",
        "}",
    ])
    write(f"data/{NAMESPACE}/function/internal/settings.mcfunction", settings())
    write(f"data/{NAMESPACE}/function/internal/reset.mcfunction", reset())
    write(f"data/{NAMESPACE}/loot_table/map.json", [
        "{",
        '    "type": "minecraft:chest",',
        '    "pools": [',
        "        {",
        '            "rolls": 1,',
        '            "entries": [',
        "                {",
        '                    "type": "minecraft:item",',
        '                    "name": "minecraft:filled_map",',
        '                    "modifier": [',
        "                        {",
        '                            "type": "minecraft:exploration_map",',
        '                            "destination": "#minecraft:village",',
        '                            "decoration": "minecraft:target_x",',
        '                            "zoom": 1,',
        '                            "search_radius": 64,',
        '                            "skip_existing_chunks": false',
        "                        }",
        "                    ]",
        "                }",
        "            ]",
        "        }",
        "    ]",
        "}",
    ])

    mobs_camera = (X0 + 0.5, GROUND + 12, Z0 + 0.5, 0, 25)
    wall_camera = (X0 + 0.5, GROUND + 6.4, Z0 + 0.5, 0, 0)
    scene("mob_pen_static", "500 mixed mobs (cows, villagers, zombies) with NoAI, for repeatable runs",
          mobs_camera, mob_pen_static())
    scene("mob_pen_live", "The same 500 mobs with AI in 1x1 barrier pens, so walk animations run",
          mobs_camera, mob_pen_live())
    scene("storage_room", "1,000 closed chests and 300 signs with text",
          (X0 + 0.5, GROUND + 7.88, Z0 + 0.5, 0, 10), storage_room())
    scene("map_wall", "400 item frames with filled maps, plus 120 shelves with items",
          wall_camera, map_wall())
    scene("display_build", "A decoration built from 400 block displays and 100 item displays",
          wall_camera, display_build())
    scene("control", "Empty superflat, nothing to accelerate", wall_camera, [])
    # Not a benchmark scene: the self-check compares vanilla and Mobium on every cached type here.
    scene("cache_gallery", "Every type the static cache handles, for pixel comparisons",
          (X0 + 0.5, GROUND + 2.6, Z0 + 0.5, 0, 12), cache_gallery())


if __name__ == "__main__":
    main()
